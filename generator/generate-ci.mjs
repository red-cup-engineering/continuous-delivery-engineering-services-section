// Caller generator (requirement 18): selects node-package, lean and content from
// a repository's files and writes short callers under .github/workflows/.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const REUSABLE = 'red-cup-engineering/continuous-delivery-services-section/.github/workflows';
export const REF = 'main';
// Mirrors content.yml's walk, so selection matches what content.yml would check.
const SKIP = new Set(['.git', 'node_modules', '.lake', 'lib']);

function walk(root, dir = '.') {
  return fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap(e => {
    if (SKIP.has(e.name)) return [];
    const rel = path.join(dir, e.name);
    return e.isDirectory() ? walk(root, rel) : [rel];
  });
}

function hasRelativeSchema(file) {
  let j;
  try { j = JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return false; }
  return !!j && typeof j === 'object' && typeof j.$schema === 'string' && !/^https?:/.test(j.$schema);
}

function hasRelativeLink(file) {
  const t = fs.readFileSync(file, 'utf8').replace(/```[\s\S]*?```/g, '');
  for (const m of t.matchAll(/\]\(([^)\s#]+)(?:#[^)]*)?\)/g)) if (!/^[a-z]+:/i.test(m[1])) return true;
  return false;
}

// Returns {node: bool, lean: [workingDirectory...], content: bool}.
export function detect(root) {
  const files = walk(root);
  const base = f => path.basename(f);
  const lean = files.filter(f => /^lakefile\.(lean|toml)$/.test(base(f)))
    .map(f => path.dirname(f)).filter((d, i, a) => a.indexOf(d) === i).sort();
  return {
    node: files.some(f => base(f) === 'package.json'),
    lean,
    content: files.some(f => {
      const abs = path.join(root, f);
      return (f.endsWith('.json') && hasRelativeSchema(abs)) || (f.endsWith('.md') && hasRelativeLink(abs));
    }),
  };
}

const job = (id, file, withs = {}) => {
  const w = Object.entries(withs).map(([k, v]) => `      ${k}: ${v}\n`).join('');
  return `  ${id}:\n    uses: ${REUSABLE}/${file}@${REF}\n` + (w ? `    with:\n${w}` : '');
};

export function renderCi(sel) {
  const jobs = [];
  if (sel.node) jobs.push(job('node-package', 'node-package.yml'));
  sel.lean.forEach(d => jobs.push(job(
    d === '.' ? 'lean' : 'lean-' + d.replace(/[^A-Za-z0-9]+/g, '-'), 'lean.yml', { 'working-directory': d })));
  if (sel.content) jobs.push(job('content', 'content.yml'));
  if (!jobs.length) return null;
  return `# Generated by continuous-delivery-services-section/generator. Do not hand-write CI.\nname: ci\non: [push, pull_request]\njobs:\n${jobs.join('')}`;
}

// change-test.yml: a package repository's pull requests are tested against every machine that pins it
// (change-test.yml discovers them); the caller passes the house read token by inheritance.
export function renderChangeTest(sel) {
  if (!sel.node) return null;
  return `# Generated by continuous-delivery-services-section/generator. Do not hand-write CI.\nname: change-test\non: pull_request\njobs:\n  change-test:\n    uses: ${REUSABLE}/change-test.yml@${REF}\n    secrets: inherit\n`;
}

// sync.yml: the downward chain (a repository with submodules advances them) and,
// with a parent, the upward chain (a push to main notifies the parent).
export function renderSync({ submodules, parent }) {
  if (!submodules && !parent) return null;
  const on = ['on:'];
  if (submodules) on.push('  schedule:', "    - cron: '17 6 * * *'", '  repository_dispatch:', '    types: [section-advanced]', '  workflow_dispatch:');
  if (parent) on.push('  push:', '    branches: [main]');
  const jobs = [];
  if (submodules) jobs.push(`  advance:\n    if: github.event_name != 'push'\n    uses: ${REUSABLE}/superrepo-advance.yml@${REF}\n    with:\n      source: \${{ github.event.client_payload.repository }}\n    secrets: inherit\n`);
  if (parent) jobs.push(`  notify:\n    if: github.event_name == 'push'\n    uses: ${REUSABLE}/notify-parent.yml@${REF}\n    with:\n      parent: ${parent}\n    secrets: inherit\n`);
  return `# Generated by continuous-delivery-services-section/generator.\nname: sync\n${on.join('\n')}\njobs:\n${jobs.join('')}`;
}

// Handwritten workflows other than the generated ones, each against the reusable
// workflow that covers it (requirement 17). Removal waits on the receiving office.
export function reportHandwritten(root) {
  const dir = path.join(root, '.github/workflows');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => /\.ya?ml$/.test(f) && !['ci.yml', 'sync.yml', 'change-test.yml'].includes(f)).map(f => {
    const t = fs.readFileSync(path.join(dir, f), 'utf8');
    if (t.includes(REUSABLE)) return { file: f, coveredBy: null, note: 'already a caller' };
    const coveredBy = /lake|lean-action|leanprover/.test(t) ? 'lean.yml'
      : /\b(npm|pnpm|yarn|setup-node)\b/.test(t) ? 'node-package.yml'
      : /\$schema|markdown|link/i.test(t) ? 'content.yml'
      : /gitmodules|submodule/i.test(t) ? 'submodule-advance.yml' : null;
    return { file: f, coveredBy, note: coveredBy ? 'duplicate pending confirmation' : 'no reusable workflow covers it' };
  });
}

// Returns {files: {path: content}, handwritten, selection}. Writes nothing.
export function generate(root, { parent } = {}) {
  const selection = detect(root);
  const files = {};
  const ci = renderCi(selection);
  if (ci) files['.github/workflows/ci.yml'] = ci;
  const changeTest = renderChangeTest(selection);
  if (changeTest) files['.github/workflows/change-test.yml'] = changeTest;
  const sync = renderSync({ submodules: fs.existsSync(path.join(root, '.gitmodules')), parent });
  if (sync) files['.github/workflows/sync.yml'] = sync;
  return { files, handwritten: reportHandwritten(root), selection };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const args = process.argv.slice(2);
  const opt = n => { const i = args.indexOf(n); return i < 0 ? undefined : args[i + 1]; };
  const root = path.resolve(args.find((a, i) => !a.startsWith('--') && !['--parent', '--pr', '--only'].includes(args[i - 1])) ?? '.');
  const generated = generate(root, { parent: opt('--parent') });
  const { handwritten, selection } = generated;
  // --only NAME keeps one caller (e.g. change-test), for a rollout that introduces a single standard.
  const files = opt('--only') ? Object.fromEntries(Object.entries(generated.files).filter(([p]) => p === `.github/workflows/${opt('--only')}.yml`)) : generated.files;
  console.log('selected:', JSON.stringify(selection));
  for (const h of handwritten) console.log(`handwritten ${h.file}: ${h.coveredBy ?? '-'} (${h.note})`);
  if (args.includes('--pr')) {
    const { openPullRequest } = await import('./open-pr.mjs');
    const url = await openPullRequest({ repo: opt('--pr'), files, token: process.env.GH_TOKEN });
    console.log('pull request:', url);
  } else {
    for (const [p, c] of Object.entries(files)) {
      fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
      fs.writeFileSync(path.join(root, p), c);
      console.log('wrote', p);
    }
    if (!Object.keys(files).length) console.log('nothing selected; no caller written');
  }
}
